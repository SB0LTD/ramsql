"""Differential COPY suite against native PostgreSQL (design §5.17(d), step 5.1).

Each case runs the same COPY FROM STDIN / COPY TO STDOUT traffic through
psycopg on the reference image and on RAMSQL and compares SQLSTATEs, command
tags, row values and (COPY TO) the exact output bytes: text escapes, CSV
HEADER and quoting, psycopg binary COPY, column subsets with defaults and
identity, malformed rows (22P04 / 22P02 / 23505 / 23502) each followed by an
unchanged count, CopyFail (57014), a socket shut down mid-COPY, COPY inside a
rolled-back transaction, a CopyData message larger than 64 KiB and rows split
across messages.

The default profile also runs a 5 000-row COPY that RAMSQL rejects at its
documented row capacity while the reference succeeds: it is reported under
`divergences` (asserting the RAMSQL error leaves the table unchanged) and is
never counted as parity. `--large` instead expects a binary built with
`sig build -Drows=32768 -Dtables=2 -Dtext-bytes=64 -Dtx-writes=32768
-Dtransaction-bytes=4194304` and imports/exports 30 000 rows (with a durable
kill and restart under --durable), recording RAMSQL's peak committed memory.

    python tools/test_postgres_copy.py --image postgres:18-alpine --report <path>
    python tools/test_postgres_copy.py --durable --scram --report <path>

Exit codes: 0 every case matches; 1 differences; 2 harness error.
Matching these cases does not establish full PostgreSQL COPY parity.
"""

