def copy_in(connection, sql, data=b"", *, rows=(), types=None):
    """psycopg COPY FROM STDIN: rows via write_row (with set_types), raw data via write."""
    try:
        with connection.cursor() as cursor:
            with cursor.copy(sql) as copy:
                if types:
                    copy.set_types(types)
                for row in rows:
                    copy.write_row(row)
                if data:
                    copy.write(data)
            return {"sqlstate": "00000", "rowcount": cursor.rowcount, "status": cursor.statusmessage}
    except Exception as error:  # noqa: BLE001 - compared by SQLSTATE
        return error_result(error)


def copy_raw(connection, sql, chunks, fail=None):
    """One CopyData message per chunk (no client buffering), then CopyDone or CopyFail."""
    from psycopg import generators
    try:
        with connection.cursor() as cursor:
            connection.wait(cursor._start_copy_gen(sql, None))
            for chunk in chunks:
                connection.wait(generators.copy_to(connection.pgconn, chunk, True))
            result = connection.wait(generators.copy_end(connection.pgconn, fail))
            return {"sqlstate": "00000", "status": result.command_status.decode()}
    except Exception as error:  # noqa: BLE001 - compared by SQLSTATE
        return error_result(error)


def copy_out(connection, sql):
    """COPY TO STDOUT: the concatenated CopyData bytes (compared exactly)."""
    try:
        with connection.cursor() as cursor:
            with cursor.copy(sql) as copy:
                data = b"".join(bytes(block) for block in copy)
            return {"sqlstate": "00000", "status": cursor.statusmessage, "rowcount": cursor.rowcount,
                    "length": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                    "head": data[:2048].hex()}
    except Exception as error:  # noqa: BLE001 - compared by SQLSTATE
        return error_result(error)


def ev(sql, outcome):
    return {"sql": sql, "outcome": outcome}


