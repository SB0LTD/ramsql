def drop(psycopg, arguments):
    with psycopg.connect(**arguments) as connection:
        execute(connection, "ROLLBACK")
        for name in TABLES:
            execute(connection, "DROP TABLE " + name)


def run(psycopg, arguments, function, *extra):
    drop(psycopg, arguments)
    try:
        with psycopg.connect(**arguments) as connection:
            result = function(connection, psycopg, arguments, *extra)
            return result if isinstance(result, dict) else {"events": result}
    finally:
        drop(psycopg, arguments)


def rows_data(count, start=0):
    return b"".join(b"%d\tlabel-%08d\n" % (index, index) for index in range(start, start + count))


def capacity_case(connection, psycopg, arguments):
    return [ev(T, execute(connection, T)),
            ev("COPY 5000 rows", copy_in(connection, "COPY cp_t FROM STDIN", rows_data(5000))),
            ev(COUNT, execute(connection, COUNT))]


def large_case(connection, psycopg, arguments, restart):
    """30 000 rows in and out; after a crash restart (durable) the same again."""
    events = [ev(T, execute(connection, T)),
              ev("COPY 30000 rows", copy_in(connection, "COPY cp_t FROM STDIN", rows_data(30000))),
              ev(COUNT, execute(connection, COUNT)),
              ev("sum", execute(connection, "SELECT sum(id), min(label), max(label) FROM cp_t")),
              ev("export", copy_out(connection, "COPY cp_t TO STDOUT"))]
    result = {"events": events}
    if restart is not None:
        connection.close()
        restart()
        with psycopg.connect(**arguments) as again:
            result["after_restart"] = [ev(COUNT, execute(again, COUNT)),
                                       ev("export", copy_out(again, "COPY cp_t TO STDOUT"))]
    return result


def peak_commit(port):
    """Peak private commit and working set of the process listening on `port` (Windows)."""
    if os.name != "nt":
        return {"measured": False, "reason": "peak commit is measured on Windows only"}
    import ctypes
    import ctypes.wintypes as w

    class Counters(ctypes.Structure):
        _fields_ = [("cb", w.DWORD), ("PageFaultCount", w.DWORD), ("PeakWorkingSetSize", ctypes.c_size_t),
                    ("WorkingSetSize", ctypes.c_size_t), ("QuotaPeakPagedPoolUsage", ctypes.c_size_t),
                    ("QuotaPagedPoolUsage", ctypes.c_size_t), ("QuotaPeakNonPagedPoolUsage", ctypes.c_size_t),
                    ("QuotaNonPagedPoolUsage", ctypes.c_size_t), ("PagefileUsage", ctypes.c_size_t),
                    ("PeakPagefileUsage", ctypes.c_size_t), ("PrivateUsage", ctypes.c_size_t)]
    owner = subprocess.run(["powershell", "-NoProfile", "-Command",
                            f"(Get-NetTCPConnection -LocalPort {port} -State Listen).OwningProcess"],
                           capture_output=True, text=True, timeout=30).stdout.split()
    if not owner:
        return {"measured": False, "reason": "listener process not found"}
    pid = int(owner[0])
    handle = ctypes.windll.kernel32.OpenProcess(0x0410, False, pid)
    counters = Counters()
    counters.cb = ctypes.sizeof(Counters)
    ctypes.windll.psapi.GetProcessMemoryInfo(handle, ctypes.byref(counters), counters.cb)
    ctypes.windll.kernel32.CloseHandle(handle)
    return {"measured": True, "pid": pid, "peak_private_commit_bytes": counters.PeakPagefileUsage,
            "private_commit_bytes": counters.PrivateUsage, "peak_working_set_bytes": counters.PeakWorkingSetSize}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--binary", type=Path, default=ROOT / "sig-out" / "bin" / ("ramsql.exe" if os.name == "nt" else "ramsql"))
    parser.add_argument("--image", default="postgres:18-alpine", help="locally available immutable reference image (no automatic pull)")
    parser.add_argument("--work-dir", type=Path, default=ROOT / ".sig-cache" / "postgres-compat")
    parser.add_argument("--report", type=Path, default=ROOT / ".sig-cache" / "postgres-compat" / "copy-report.json")
    parser.add_argument("--durable", action="store_true", help="run RAMSQL on a fresh durable WAL instead of --memory")
    parser.add_argument("--scram", action="store_true", help="run RAMSQL with a generated SCRAM-SHA-256 verifier")
    parser.add_argument("--large", action="store_true", help="30 000-row import/export against a large-profile --binary")
    parser.add_argument("--case", action="append", default=[], help="run only the named case(s)")
    args = parser.parse_args()
    timezone_dir = reference_timezone_dir(args.image)
    import psycopg

    binary = args.binary.resolve()
    report = {"schema": 1, "started_utc": datetime.now(timezone.utc).isoformat(),
              "scope": "finite differential COPY cases; matching does not establish full PostgreSQL COPY parity",
              "ramsql_binary": str(binary), "ramsql_sha256": hashlib.sha256(binary.read_bytes()).hexdigest(),
              "client": {"name": "psycopg", "version": psycopg.__version__}, "large": args.large,
              "cases": [], "divergences": []}
    try:
        with native_postgres(args.image, psycopg, work_directory=args.work_dir) as (native, metadata), \
                candidate_mode(args.work_dir, durable=args.durable, scram=args.scram, timezone_dir=timezone_dir) as (mode_arguments, mode):
            report["reference"] = metadata
            report["mode"] = mode
            report["reference_image"] = {"id": metadata.get("image_id"), "repo_digests": metadata.get("image_digests")}
            candidate = Candidate(binary, mode_arguments)
            candidate.start()
            try:
                if args.large:
                    started = time.monotonic()
                    reference_result = run(psycopg, native, large_case, (lambda: restart_native(native, metadata, psycopg)) if args.durable else None)
                    reference_seconds = time.monotonic() - started
                    started = time.monotonic()
                    candidate_result = run(psycopg, candidate.connection, large_case, candidate.restart if args.durable else None)
                    candidate_seconds = time.monotonic() - started
                    if not args.durable:
                        reference_result.pop("after_restart", None)
                        candidate_result.pop("after_restart", None)
                    gaps = differences(reference_result, candidate_result)
                    report["cases"].append({"name": "large_30000_rows", "match": not gaps, "differences": gaps,
                                            "postgres": reference_result, "ramsql": candidate_result,
                                            "seconds": {"postgres": round(reference_seconds, 3), "ramsql": round(candidate_seconds, 3)}})
                    report["ramsql_memory"] = peak_commit(candidate.connection["port"])
                    print(("PASS" if not gaps else "GAP ") + " large_30000_rows" + ("" if not gaps else ": " + gaps[0]["path"]))
                else:
                    for name, function in CASES:
                        if args.case and name not in args.case:
                            continue
                        reference_result = run(psycopg, native, function)
                        candidate_result = run(psycopg, candidate.connection, function)
                        gaps = differences(reference_result, candidate_result)
                        report["cases"].append({"name": name, "match": not gaps, "differences": gaps,
                                                "postgres": reference_result, "ramsql": candidate_result})
                        print(("PASS" if not gaps else "GAP ") + " " + name + ("" if not gaps else ": " + gaps[0]["path"]))
                    if not args.case or "default_profile_capacity" in args.case:
                        reference_result = run(psycopg, native, capacity_case)
                        candidate_result = run(psycopg, candidate.connection, capacity_case)
                        ref_copy, ram_copy = reference_result["events"][1]["outcome"], candidate_result["events"][1]["outcome"]
                        ram_count = candidate_result["events"][2]["outcome"].get("rows")
                        documented = (ref_copy.get("status") == "COPY 5000" and ram_copy.get("sqlstate") == "54000"
                                      and ram_count == [[0]])
                        report["divergences"].append({
                            "name": "default_profile_capacity_5000_rows",
                            "kind": "documented capacity divergence (not parity)",
                            "expected": "reference COPY 5000; RAMSQL rejects with RowCapacity 54000 at its row capacity (rows 512, below tx-writes 4096) with the table unchanged",
                            "as_documented": documented, "postgres": reference_result, "ramsql": candidate_result})
                        print(("DIVERGENCE (as documented)" if documented else "DIVERGENCE UNEXPECTED") +
                              " default_profile_capacity_5000_rows: RAMSQL " + str(ram_copy.get("sqlstate")))
                        if not documented:
                            report["cases"].append({"name": "default_profile_capacity_5000_rows", "match": False,
                                                    "differences": [{"path": "/divergence", "postgres": ref_copy, "ramsql": ram_copy}]})
            finally:
                candidate.stop()
        mismatching = sum(not case["match"] for case in report["cases"])
        report["summary"] = {"executed": len(report["cases"]), "matching": len(report["cases"]) - mismatching,
                             "mismatching": mismatching, "divergences": len(report["divergences"]), "passed": mismatching == 0}
        result = 1 if mismatching else 0
    except Exception as error:  # noqa: BLE001 - recorded in the report
        report["harness_error"] = {"class": type(error).__name__, "message": str(error)}
        report["summary"] = {"executed": len(report["cases"]), "passed": False, "incomplete": True}
        print("HARNESS ERROR: " + type(error).__name__ + ": " + str(error), file=sys.stderr)
        result = 2
    report["finished_utc"] = datetime.now(timezone.utc).isoformat()
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(json_value(report), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps(report["summary"], sort_keys=True))
    print("Report: " + str(args.report.resolve()))
    return result


