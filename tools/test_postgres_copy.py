def case_socket_killed(connection, psycopg, arguments):
    events = [ev(T, execute(connection, T))]
    victim = psycopg.connect(**arguments)
    method = "shutdown"
    try:
        with victim.cursor() as cursor:
            victim.wait(cursor._start_copy_gen("COPY cp_t FROM STDIN", None))
            from psycopg import generators
            victim.wait(generators.copy_to(victim.pgconn, b"1\tgone\n2\tgone\n", True))
            try:
                raw = socket.socket(fileno=victim.pgconn.socket)
                raw.shutdown(socket.SHUT_RDWR)
                raw.detach()
            except OSError:
                method = "finish"
                victim.pgconn.finish()
    finally:
        try:
            victim.close()
        except Exception:  # noqa: BLE001 - the socket is gone on purpose
            pass
    time.sleep(0.3)
    events.append(ev("socket killed mid-COPY (" + method + ")", {"sqlstate": "00000"}))
    events.append(ev(COUNT, execute(connection, COUNT)))
    events.append(ev("reconnect COPY", copy_in(connection, "COPY cp_t FROM STDIN", b"1\tback\n")))
    events.append(ev(ROWS_T, execute(connection, ROWS_T)))
    return events


