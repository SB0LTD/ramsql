def case_errors(connection, psycopg, arguments):
    events = [ev(T, execute(connection, T)), ev("seed", copy_in(connection, "COPY cp_t FROM STDIN", b"1\tone\n"))]
    for name, data in (("missing column", b"2\ttwo\n3\n"), ("extra column", b"2\ttwo\n3\tthree\tx\n"),
                       ("bad integer", b"2\ttwo\nthree\tx\n"), ("duplicate in copy", b"2\ttwo\n2\tagain\n"),
                       ("duplicate committed", b"2\ttwo\n1\tagain\n"), ("int4 overflow", b"2\ttwo\n99999999999\tx\n")):
        events.append(ev(name, copy_in(connection, "COPY cp_t FROM STDIN", data)))
        events.append(ev(COUNT, execute(connection, COUNT)))
    for sql in ("COPY cp_t FROM STDIN (FORMAT binary, DELIMITER ',')", "COPY cp_t FROM STDIN (DELIMITER 'ab')",
                "COPY cp_t FROM STDIN (FORMAT xml)", "COPY cp_t FROM STDIN (QUOTE '\"')",
                "COPY cp_t FROM STDIN (FORMAT csv, DELIMITER ',', QUOTE ',')", "COPY missing FROM STDIN",
                "COPY cp_t TO STDOUT (FORMAT csv, HEADER match)"):
        events.append(ev(sql, copy_in(connection, sql, b"5\tx\n")))
    events.append(ev(COUNT, execute(connection, COUNT)))
    return events


